function adminLang() {
  return typeof StoreState !== 'undefined' ? StoreState.getLang() : 'ar';
}

function t(key) {
  const lang = adminLang();
  return (ADMIN_I18N[lang] && ADMIN_I18N[lang][key]) || ADMIN_I18N.ar[key] || key;
}

function applyAdminDir() {
  const lang = adminLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'en' ? 'ltr' : 'rtl';
  document.body.classList.toggle('is-ltr', lang === 'en');
}
